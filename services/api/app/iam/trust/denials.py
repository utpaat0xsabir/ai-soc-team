"""Structural errors only; these codes are not IAM authorization decisions."""
from enum import Enum


class StructuralCode(str, Enum):
    MISSING_REQUIRED_FIELD = 'MISSING_REQUIRED_FIELD'
    UNSUPPORTED_SCHEMA_VERSION = 'UNSUPPORTED_SCHEMA_VERSION'
    INVALID_IDENTIFIER = 'INVALID_IDENTIFIER'
    INVALID_DEPLOYMENT_TYPE = 'INVALID_DEPLOYMENT_TYPE'
    INVALID_DEPLOYMENT_IDENTITY = 'INVALID_DEPLOYMENT_IDENTITY'
    INVALID_DEPLOYMENT_BINDING = 'INVALID_DEPLOYMENT_BINDING'
    INVALID_TENANT_BINDING = 'INVALID_TENANT_BINDING'
    INVALID_ISSUER_REFERENCE = 'INVALID_ISSUER_REFERENCE'
    INVALID_QUORUM_CONFIGURATION = 'INVALID_QUORUM_CONFIGURATION'
    DUPLICATE_CUSTODIAN = 'DUPLICATE_CUSTODIAN'
    INVALID_ROOT_POLICY_VERSION = 'INVALID_ROOT_POLICY_VERSION'
    INVALID_PROVIDER_DELEGATION = 'INVALID_PROVIDER_DELEGATION'
    INVALID_CHECKPOINT_REFERENCE = 'INVALID_CHECKPOINT_REFERENCE'
    INVALID_RECOVERY_JOURNAL_REFERENCE = 'INVALID_RECOVERY_JOURNAL_REFERENCE'
    INVALID_TIMESTAMP = 'INVALID_TIMESTAMP'
    INVALID_AUTHORITY_SCOPE = 'INVALID_AUTHORITY_SCOPE'
    INVALID_AUTHORITY_REVISION = 'INVALID_AUTHORITY_REVISION'
    UNSUPPORTED_OPERATION = 'UNSUPPORTED_OPERATION'
    MALFORMED_PROVENANCE_ENVELOPE = 'MALFORMED_PROVENANCE_ENVELOPE'
    NONCANONICAL_REPRESENTATION = 'NONCANONICAL_REPRESENTATION'


class StructuralError(ValueError):
    """Never retain validation input, driver text or claimed trust assertions."""
    def __init__(self, code: StructuralCode):
        self.code = StructuralCode(code)
        super().__init__(self.code.value)
